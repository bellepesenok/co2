def set_cell_bg(cell, hex_color):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def style_run(run, font=CN_FONT, size=11, bold=False, color=None, italic=False):
    run.font.name = font
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:eastAsia"), font)
    rfonts.set(qn("w:ascii"), font)
    rfonts.set(qn("w:hAnsi"), font)


def add_para(doc, runs, align=None, space_after=4, space_before=0, left_indent=None):
    """runs = список кортежей (текст, опции-словарь)"""
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    if left_indent is not None:
        pf.left_indent = Cm(left_indent)
    for text, opts in runs:
        r = p.add_run(text)
        style_run(r, **opts)
    return p


def add_title(doc, cn, ru):
    p = add_para(doc, [(cn, dict(font=CN_FONT, size=22, bold=True, color=C_TITLE))],
                 align=WD_ALIGN_PARAGRAPH.CENTER, space_after=2)
    add_para(doc, [(ru, dict(font=RU_FONT, size=12, italic=True, color=C_RU))],
             align=WD_ALIGN_PARAGRAPH.CENTER, space_after=10)


def add_h1(doc, num, cn, ru):
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    p = add_para(doc, [(f"{num}  {cn}", dict(font=CN_FONT, size=16, bold=True, color=C_H1))],
                 space_before=6, space_after=2)
    add_para(doc, [(ru, dict(font=RU_FONT, size=10.5, italic=True, color=C_H1))], space_after=6)
    # подчёркивающая линия
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "8")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "0B5294")
    pbdr.append(bottom)
    pPr.append(pbdr)


def add_h2(doc, cn, ru=None):
    runs = [(cn, dict(font=CN_FONT, size=13, bold=True, color=C_H2))]
    if ru:
        runs.append(("  ｜ " + ru, dict(font=RU_FONT, size=10, italic=True, color=C_H2)))
    add_para(doc, runs, space_before=6, space_after=3)


def add_h3(doc, cn, ru=None):
    runs = [(cn, dict(font=CN_FONT, size=11.5, bold=True, color=RGBColor(0x33, 0x33, 0x33)))]
    if ru:
        runs.append(("  — " + ru, dict(font=RU_FONT, size=9.5, italic=True, color=RGBColor(0x88, 0x88, 0x88))))
    add_para(doc, runs, space_before=3, space_after=2)


def bullet(doc, cn, level=0, key=False):
    color = C_KEY if key else RGBColor(0x22, 0x22, 0x22)
    mark = "● " if level == 0 else ("– " if level == 1 else "· ")
    add_para(doc, [(mark + cn, dict(font=CN_FONT, size=10.5, bold=key, color=color))],
             space_after=2, left_indent=0.6 + level * 0.6)


def ru_box(doc, title, lines):
    """Блок глубокого пояснения на русском (таблица с фоном)."""
    table = doc.add_table(rows=1, cols=1)
    table.style = "Table Grid"
    cell = table.cell(0, 0)
    set_cell_bg(cell, C_RUBG)
    cell.paragraphs[0].text = ""
    p0 = cell.paragraphs[0]
    p0.paragraph_format.space_after = Pt(3)
    r = p0.add_run("🔎 Пояснение (RU): " + title)
    style_run(r, font=RU_FONT, size=10.5, bold=True, color=C_RU)
    for ln in lines:
        p = cell.add_paragraph()
        p.paragraph_format.space_after = Pt(2)
        r = p.add_run(ln)
        style_run(r, font=RU_FONT, size=10, color=RGBColor(0x33, 0x22, 0x11))
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def qa(doc, q_cn, a_lines):
    """Развёрнутый вопрос-ответ для устной части."""
    add_para(doc, [("❓ " + q_cn, dict(font=CN_FONT, size=10.5, bold=True, color=RGBColor(0x5B, 0x2C, 0x83)))],
             space_before=3, space_after=2)
    for ln in a_lines:
        add_para(doc, [("→ " + ln, dict(font=CN_FONT, size=10.5, color=RGBColor(0x22, 0x22, 0x22)))],
                 space_after=2, left_indent=0.6)


def add_term_table(doc, terms):
    table = doc.add_table(rows=1, cols=3)
    table.style = "Table Grid"
    hdr = table.rows[0].cells
    for c, t in zip(hdr, ["中文 / Термин", "拼音 Pinyin", "Перевод (RU)"]):
        set_cell_bg(c, "0B5294")
        p = c.paragraphs[0]
        r = p.add_run(t)
        style_run(r, font=RU_FONT, size=10, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF))
    for cn, py, ru in terms:
        cells = table.add_row().cells
        r = cells[0].paragraphs[0].add_run(cn)
        style_run(r, font=CN_FONT, size=10.5, bold=True, color=RGBColor(0x11, 0x11, 0x11))
        r = cells[1].paragraphs[0].add_run(py)
        style_run(r, font=RU_FONT, size=9.5, italic=True, color=RGBColor(0x66, 0x66, 0x66))
        r = cells[2].paragraphs[0].add_run(ru)
        style_run(r, font=RU_FONT, size=10, color=RGBColor(0x22, 0x22, 0x22))


