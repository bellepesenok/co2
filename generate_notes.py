from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

CN_FONT = "宋体"          # Chinese font
LAT_FONT = "Times New Roman"  # Latin/Cyrillic font

# ---------- цвета ----------
C_TITLE = RGBColor(0x1F, 0x38, 0x64)     # тёмно-синий
C_H1 = RGBColor(0xC0, 0x00, 0x00)        # тёмно-красный
C_H2 = RGBColor(0x1F, 0x49, 0x7D)        # синий
C_RU = RGBColor(0x1F, 0x4E, 0x2A)        # тёмно-зелёный (пояснения)
C_KEY = RGBColor(0xB0, 0x00, 0x00)       # акцент
C_GREY = RGBColor(0x44, 0x44, 0x44)

doc = Document()

# базовый стиль
style = doc.styles["Normal"]
style.font.name = LAT_FONT
style.font.size = Pt(11)
style._element.rPr.rFonts.set(qn("w:eastAsia"), CN_FONT)


def _set_run(run, font=None, size=None, bold=None, italic=None, color=None):
    if font:
        run.font.name = font
        run._element.rPr.rFonts.set(qn("w:eastAsia"), font)
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if italic is not None:
        run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color


def shade(paragraph, hex_color):
    """залить фон абзаца."""
    pPr = paragraph._p.get_or_add_pPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    pPr.append(shd)


def border_left(paragraph, hex_color, size="18"):
    pPr = paragraph._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    left = OxmlElement("w:left")
    left.set(qn("w:val"), "single")
    left.set(qn("w:sz"), size)
    left.set(qn("w:space"), "8")
    left.set(qn("w:color"), hex_color)
    pbdr.append(left)
    pPr.append(pbdr)


def title(text, sub=None):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    _set_run(r, CN_FONT, 22, bold=True, color=C_TITLE)
    if sub:
        p2 = doc.add_paragraph()
        p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r2 = p2.add_run(sub)
        _set_run(r2, LAT_FONT, 12, italic=True, color=C_GREY)


def h1(text):
    p = doc.add_paragraph()
    p.space_before = Pt(14)
    r = p.add_run(text)
    _set_run(r, CN_FONT, 16, bold=True, color=C_H1)
    shade(p, "F2DCDB")


def h2(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    _set_run(r, CN_FONT, 13.5, bold=True, color=C_H2)


def h3(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    _set_run(r, CN_FONT, 12, bold=True, color=RGBColor(0x33, 0x33, 0x33))


def bullet(parts, level=0):
    """parts: список кортежей (text, kw) для смешанного форматирования, либо строка."""
    p = doc.add_paragraph(style="List Bullet" if level == 0 else "List Bullet 2")
    if isinstance(parts, str):
        parts = [(parts, {})]
    for text, kw in parts:
        r = p.add_run(text)
        font = CN_FONT
        _set_run(r, font, kw.get("size", 11), bold=kw.get("bold"),
                 color=kw.get("color"))
    return p


def para(text, size=11, bold=None, color=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    _set_run(r, CN_FONT, size, bold=bold, color=color)
    return p


def ru(text_lines, header="俄语深度讲解 / Пояснение на русском"):
    """зелёный блок пояснения на русском."""
    hp = doc.add_paragraph()
    hp.space_before = Pt(6)
    hr = hp.add_run("▍" + header)
    _set_run(hr, LAT_FONT, 11.5, bold=True, color=C_RU)
    border_left(hp, "1F4E2A")
    shade(hp, "E8F2EC")
    for line in text_lines:
        p = doc.add_paragraph()
        border_left(p, "1F4E2A")
        shade(p, "F1F8F3")
        # поддержка жирного через **...**
        segs = line.split("**")
        for i, seg in enumerate(segs):
            if seg == "":
                continue
            r = p.add_run(seg)
            _set_run(r, LAT_FONT, 10.5, bold=(i % 2 == 1), color=RGBColor(0x20,0x35,0x28))
            r._element.rPr.rFonts.set(qn("w:eastAsia"), CN_FONT)


def keybox(text_lines, header="★ 必记考点（速记）"):
    hp = doc.add_paragraph()
    hr = hp.add_run(header)
    _set_run(hr, CN_FONT, 11.5, bold=True, color=RGBColor(0x8a,0x60,0x00))
    shade(hp, "FDF3D0")
    for line in text_lines:
        p = doc.add_paragraph()
        shade(p, "FFFBEA")
        r = p.add_run("• " + line)
        _set_run(r, CN_FONT, 10.5, color=RGBColor(0x5a,0x42,0x00))


def make_table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, htext in enumerate(headers):
        hdr[i].text = ""
        rp = hdr[i].paragraphs[0].add_run(htext)
        _set_run(rp, CN_FONT, 10.5, bold=True, color=RGBColor(0xFF,0xFF,0xFF))
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            rp = cells[i].paragraphs[0].add_run(val)
            _set_run(rp, CN_FONT, 10)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    return t


def spacer():
    doc.add_paragraph()


