def set_run_font(run, font=CN_FONT, size=10.5, bold=False, color=None, italic=False):
    run.font.name = font
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:eastAsia"), font)
    rfonts.set(qn("w:ascii"), font)
    rfonts.set(qn("w:hAnsi"), font)


def add_par(text="", size=10.5, bold=False, color=None, font=CN_FONT,
            before=0, after=2, align=None, indent=None, italic=False):
    p = doc.add_paragraph()
    if before:
        p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    if align is not None:
        p.alignment = align
    if indent is not None:
        p.paragraph_format.left_indent = Cm(indent)
    if text:
        r = p.add_run(text)
        set_run_font(r, font=font, size=size, bold=bold, color=color, italic=italic)
    return p


def add_runs(parts, size=10.5, before=0, after=2, indent=None):
    """parts: list of (text, {opts})"""
    p = doc.add_paragraph()
    if before:
        p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    if indent is not None:
        p.paragraph_format.left_indent = Cm(indent)
    for text, opts in parts:
        r = p.add_run(text)
        set_run_font(r, font=opts.get("font", CN_FONT), size=opts.get("size", size),
                     bold=opts.get("bold", False), color=opts.get("color"),
                     italic=opts.get("italic", False))
    return p


