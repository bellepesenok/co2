def bullet(segments, level=0):
    """segments: str OR list of (text, bold) tuples."""
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.left_indent = Cm(0.6 + 0.5 * level)
    if isinstance(segments, str):
        segments = [(segments, False)]
    for text, bold in segments:
        r = p.add_run(text)
        set_run(r)
        r.font.size = Pt(11)
        r.bold = bold
        if bold:
            r.font.color.rgb = C_KEY
    return p


def para(text, bold=False, size=11):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_run(r)
    r.font.size = Pt(size)
    r.bold = bold
    return p


def ru_box(text_lines, header="Пояснение (俄语解析)"):
    """绿色俄语解析框"""
    ph = doc.add_paragraph()
    shade_paragraph(ph, SHADE_RU)
    add_border(ph, "6FA03C")
    rh = ph.add_run("▍ " + header)
    set_run(rh)
    rh.bold = True
    rh.font.size = Pt(10.5)
    rh.font.color.rgb = C_RU
    for line in text_lines:
        pl = doc.add_paragraph()
        shade_paragraph(pl, SHADE_RU)
        add_border(pl, "6FA03C")
        pl.paragraph_format.left_indent = Cm(0.2)
        rl = pl.add_run(line)
        set_run(rl)
        rl.font.size = Pt(10.5)
        rl.font.color.rgb = RGBColor(0x26, 0x40, 0x14)


def tip_box(text):
    p = doc.add_paragraph()
