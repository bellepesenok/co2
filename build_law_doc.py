def label_para(label, text):
    p = doc.add_paragraph()
    r1 = p.add_run(label)
    set_cn_font(r1, font=CN_FONT, size=11, bold=True, color=(0xB0, 0x1F, 0x24))
    r2 = p.add_run(text)
    set_cn_font(r2, font=CN_FONT, size=11)
