h3("案例 1：沉默欺诈")
label_para("核心事实：", "甲（卖方，专业家具商）向乙（买方）出售一套实木沙发，明知沙发内部框架有严重开裂（会影响使用年限），且依家具行业惯例，卖方需告知此类核心质量问题，却故意隐瞒未说。乙购后发现开裂，诉请撤销合同。")
label_para("争议焦点：", "甲的沉默是否构成欺诈？")
label_para("分析：", "甲的沉默构成欺诈，乙有权撤销合同并索赔。依家具行业惯例，需向买方告知沙发核心质量问题，其明知沙发框架开裂却故意隐瞒，主观上具有欺诈故意，属于“应予披露而欺诈性未披露”。因此，乙的诉请成立，可宣告合同无效，要求甲返还货款并赔偿损失。")

h3("案例 2：积极欺诈")
label_para("核心事实：", "中国 A 公司向法国 B 公司出口一批羽绒服，故意在合同中谎称“羽绒服填充物为 90% 白鸭绒”，实际填充物为 50% 白鸭绒 + 50% 化纤，B 公司收货后发现不符，主张 A 公司欺诈。")
label_para("争议焦点：", "A 公司的虚假陈述是否构成欺诈？")
label_para("分析：", "构成欺诈。A 公司故意谎称羽绒服填充物比例，主观上有欺诈故意，该虚假陈述直接诱使 B 公司订立合同，且实际填充物与约定严重不符，已构成根本违约。因此，B 公司可依法宣告合同无效、拒收货物，并要求 A 公司赔偿相应损失。")

h3("案例 3：信用证欺诈")
label_para("核心事实：", "丙公司与丁公司签订钢材买卖合同，约定以信用证付款。丁公司未实际交付任何钢材，却伪造全套符合信用证要求的提单、发票等单据，向银行申请付款，丙公司发现后申请法院止付。")
label_para("争议焦点：", "丁公司的行为是否构成信用证欺诈，法院能否下令止付？")
label_para("分析：", "构成信用证欺诈，法院有权下令止付。本案中，丁公司未实际交付任何钢材，属于无真实基础交易，且伪造全套单据申请付款，主观上具有欺诈故意，行为符合“实质性重大欺诈”的认定标准。因此，丙公司可向法院申请止付，法院应依法禁止银行向丁公司支付信用证款项。")

h3("案例 4：第三人欺诈")
label_para("核心事实：", "甲与乙签订设备买卖合同，约定甲向乙供应生产设备。甲的合作伙伴丙（第三人）为促成交易，故意向乙虚假陈述“该设备可达到行业顶级生产效率”，甲对此知情但未阻止，乙基于该陈述与甲缔约，后续发现设备效率未达标，主张甲构成欺诈。")
label_para("争议焦点：", "第三人丙的欺诈行为，能否认定甲构成欺诈？")
label_para("分析：", "本案中第三人丙实施欺诈，但合同相对人甲对该欺诈知情且未予阻止（默许利用）。第三人欺诈的处理规则：若合同一方（甲）知道或应当知道第三人的欺诈行为，则视同其本人欺诈，受欺诈方（乙）有权撤销合同；若合同一方善意且不知情，则不构成可撤销事由。本案甲知情，故乙可主张撤销并请求赔偿。")

h3("案例 4 对照：非实质性内容虚假陈述")
label_para("核心事实：", "中国 C 公司向德国 D 公司出口一批儿童绘本，合同明确约定绘本的页数、印刷质量、交货时间等核心条款。C 公司为增加吸引力，在沟通中虚假陈述“该绘本曾获某国际儿童图书提名奖”（实际未获得），D 公司收货后发现该陈述虚假，主张 C 公司构成欺诈。")
label_para("分析：", "不构成欺诈，D 公司主张不成立。首先，欺诈的认定，要求虚假陈述针对合同实质性内容（如质量、数量、价款等核心条款）。本案中，合同核心条款为绘本页数、印刷质量、交货时间，C 公司虚假陈述的“获奖情况”，并非合同约定内容，也不影响 D 公司是否缔约、如何履行合同的决策，属于非实质性内容。因此，该虚假陈述虽属故意，但未达到欺诈的认定标准，不构成欺诈，D 公司仅可就该虚假陈述要求 C 公司澄清，无权主张欺诈相关救济。")

h3("案例 5：实质性内容虚假陈述")
label_para("核心事实：", "中国 C 公司向德国 D 公司出口一批儿童绘本，合同明确约定绘本为“环保无毒油墨印刷，符合欧盟儿童用品安全标准（EN 71），可正常在欧洲市场销售”。C 公司明知该批绘本使用的是非环保有毒油墨，不符合欧盟安全标准，却故意虚假陈述其为环保无毒油墨、符合相关标准，D 公司基于该陈述缔约，收货后因油墨超标无法上架销售，主张 C 公司构成欺诈。")
label_para("争议焦点：", "C 公司关于绘本的虚假陈述，是否构成欺诈？")
label_para("分析：", "构成欺诈，D 公司主张成立。根据相关规则，欺诈的核心是针对合同实质性内容的故意虚假陈述。本案中，“环保无毒油墨印刷、符合欧盟儿童用品安全标准”是合同核心条款，直接关系到 D 公司能否实现“在欧洲市场销售绘本”的交易目的，属于实质性内容。C 公司明知绘本使用非环保有毒油墨、不符合欧盟标准，却故意虚假陈述其符合约定，主观上具有欺诈故意，且该陈述直接诱使 D 公司缔约，导致 D 公司无法实现交易目的，因此构成欺诈，D 公司可宣告合同无效并要求 C 公司赔偿损失。")

# ---------------- 胁迫 ----------------
h2("第二节 胁迫（Duress）")

h3("典型胁迫的构成与效力")
para("构成典型胁迫的要件：")
bullet("有不正当威胁（以非法举报施压）；")
bullet("足以造成精神强制；")
bullet("因果关系：因害怕被举报，违背真实意思缔约。")
para("效力：")
bullet("大陆法系或中国《民法典》：可撤销；")
bullet("英美法系：人身 / 权益胁迫，可撤销；")
bullet("国际公约：相对人本人胁迫，可撤销。")

h3("案例：以举报偷税相威胁压低房价")
label_para("案情：", "甲有一套房产，乙明知甲急需用钱，故意威胁甲：不按市场价 8 折把房子卖给乙，就举报甲偷税漏税。甲迫于无奈，与乙签订房屋买卖合同。")
label_para("问题：", "乙的行为是否构成胁迫？合同效力如何？")
label_para("分析：", "构成典型胁迫：①有不正当威胁（以非法举报施压）；②足以造成精神强制；③因果关系——甲因害怕被举报，违背真实意思缔约。效力上，大陆法系 / 中国《民法典》可撤销；英美法系属人身或权益胁迫，可撤销；国际公约属相对人本人胁迫，可撤销。")

h3("案例：经济胁迫（奥斯汀诉罗尔案）")
para("判决：本案中——")
numbered("奥斯汀以停止交货作为威胁。")
