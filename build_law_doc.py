def numbered(text):
    p = doc.add_paragraph(style="List Number")
    r = p.add_run(text)
    set_cn_font(r, font=CN_FONT, size=11)
    p.paragraph_format.space_after = Pt(2)
    return p


def make_table(headers, rows):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = table.rows[0].cells
    for i, htext in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        r = p.add_run(htext)
        set_cn_font(r, font=CN_FONT_HEAD, size=10.5, bold=True, color=(0xFF, 0xFF, 0xFF))
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        tcPr = hdr[i]._tc.get_or_add_tcPr()
        shd = tcPr.makeelement(qn("w:shd"), {qn("w:val"): "clear", qn("w:fill"): "1F3B73"})
        tcPr.append(shd)
    for row in rows:
        cells = table.add_row().cells
        for i, ctext in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            r = p.add_run(ctext)
            set_cn_font(r, font=CN_FONT, size=10)
    doc.add_paragraph()
    return table


