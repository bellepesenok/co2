h3("国际商事合同通则（PICC）对第三人胁迫的规则")
para("第三人胁迫，原则不能撤；但对方知情或可归责时，可以撤。")
label_para("1) 第三人行为可归责于合同一方（= 相当于对方自己胁迫）：",
          "比如对方的员工、代理人、母公司、受控主体实施胁迫，视同对方本人胁迫，可撤销（同大陆法系）。")
label_para("2) 纯粹无关第三人胁迫，与对方无关：",
          "只有在合同相对人知道 / 应当知道第三人胁迫时，受害人才可以撤销；对方善意、不知情则不能撤销（同英美法系）。")

h3("案例：纯粹无关第三人胁迫（路人丙）")
label_para("案情：", "甲打算将车辆卖给乙，双方正常磋商。路人丙与甲有私怨，私下威胁甲：必须马上和乙签卖车合同，不然就打伤甲的孩子。甲被迫与乙签约，乙自始至终不知道丙胁迫的事，完全善意。")
label_para("问题：", "本案属于普通胁迫还是第三人胁迫？分别按大陆法系、英美法系、PICC 判断：甲能否撤销与乙的合同？")
label_para("分析：", "属于典型第三人胁迫：胁迫来自甲乙以外的第三人丙，乙无参与、不知情。规则适用：")
bullet("大陆法系（德 / 法 / 中国）：可以撤销，优先保护意思自由，不问相对人善意与否。")
bullet("英美法系：不得撤销。乙是善意无辜第三人，保护交易安全；甲只能起诉丙侵权追责。")
bullet("PICC 国际商事通则：不得撤销。纯粹无关第三人 + 相对人善意不知情，不允许撤销。")

h3("案例：受控子公司实施胁迫（可归责于相对人）")
label_para("案情：", "甲和乙公司签供货合同。乙公司的全资子公司丙，私下胁迫甲必须签约，否则断甲上下游渠道。甲被迫签约，乙公司辩称自己不知情。")
label_para("问题：", "甲能否撤销？")
label_para("分析：", "属于可归责于相对人的第三人胁迫：丙是乙的关联主体、受控主体，法律上视同乙本人实施胁迫。大陆、英美、PICC 全部一致：甲均可撤销合同。")

h3("案例：相对人明知并利用第三人胁迫")
label_para("案情：", "甲与乙洽谈商铺租赁合同。乙的好朋友丙出面威胁甲：不跟乙签约，就破坏甲的生意。乙全程在场，明知丙胁迫甲，却不制止、顺势签约。")
label_para("问题：", "是否构成第三人胁迫？甲可否撤销合同？")
label_para("分析：", "形式上是第三人丙胁迫，但相对人乙明知且利用胁迫缔约。统一规则：")
bullet("大陆法系：当然可撤销；")
bullet("英美法系：因乙知情利用，破例可撤销；")
bullet("PICC：相对人应知 / 知情，视同本人胁迫，可撤销。")

# ---------------- 不正当影响 ----------------
h2("第三节 不正当影响（英美法 Undue Influence）")
label_para("概念：", "当事人一方利用自己与另一方之间的特殊关系，通过不适当的说服另一方，使另一方接受不公平的交易条件。")
para("以不正当影响为由撤销合同，需要满足两个条件：")
bullet("当事人之间存在某种特殊的关系；")
bullet("强势的一方对弱势的一方进行了不正当的劝说，弱势一方缔约的意思表示是受到这种影响所作出的。")
label_para("典型案例：", "原告是某中学的老师。1964 年 10 月 6 日，他被指控有同性恋行为而被捕后，被警察盘问、做笔录后假释，有 40 个小时没有睡觉。随后，学区负责人以及学校校长来到他的公寓，要求它辞职，并标明他们之所以这样的要求是在帮助原告，并为原告的最大利益着想。同时，告诉原告其没有时间咨询律师。另外，校长还提到，如果原告不主动辞职，学校将对其做解雇处理，并公布其被捕原因及经过；而如果原告主动立即辞职，他们许诺不公布对原告不利的内容，并不损害原告寻找其他工作的机会。（法院据此认定构成不正当影响，原告的辞职意思表示可撤销。）")

