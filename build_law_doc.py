CN_FONT = "宋体"
CN_FONT_HEAD = "黑体"


def set_cn_font(run, font=CN_FONT, size=None, bold=None, color=None):
    run.font.name = font
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(rfonts)
    rfonts.set(qn("w:eastAsia"), font)
    rfonts.set(qn("w:ascii"), font)
    rfonts.set(qn("w:hAnsi"), font)
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if color is not None:
        run.font.color.rgb = RGBColor(*color)


doc = Document()

# 基础正文样式
normal = doc.styles["Normal"]
normal.font.name = CN_FONT
normal.font.size = Pt(11)
normal._element.get_or_add_rPr().append(
    normal._element.makeelement(qn("w:rFonts"), {qn("w:eastAsia"): CN_FONT})
)


def title(text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    set_cn_font(r, font=CN_FONT_HEAD, size=22, bold=True, color=(0x1F, 0x3B, 0x73))
    return p


