def cn(text, bold=False):
    """Абзац-конспект на китайском."""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(3)
    add_run(p, text, size=11, bold=bold)
    return p


def bullet(text, level=0, bold_lead=None):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.left_indent = Cm(0.6 + level * 0.6)
    p.paragraph_format.space_after = Pt(1)
    if bold_lead:
        add_run(p, bold_lead, size=11, bold=True, color=C_KEY)
    add_run(p, text, size=11)
    return p


def kv(key, value):
    """Строка вида «ключ：значение» (ключ выделен)."""
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.4)
    p.paragraph_format.space_after = Pt(2)
    add_run(p, key, size=11, bold=True, color=C_KEY)
    add_run(p, value, size=11)
    return p


def ru(text, label="俄文讲解 / Пояснение на русском"):
    """Блок глубокого пояснения на русском с заливкой и боковой полосой."""
    ph = doc.add_paragraph()
    ph.paragraph_format.space_before = Pt(6)
    ph.paragraph_format.space_after = Pt(0)
    shade(ph, "EAF3EC")
    left_border(ph, "1A4D2E")
    add_run(ph, "💡 " + label, size=10, bold=True, color=C_RU)

    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(8)
    shade(p, "EAF3EC")
    left_border(p, "1A4D2E")
    add_run(p, text, size=10.5, color=RGBColor(0x20, 0x20, 0x20))
    return p


