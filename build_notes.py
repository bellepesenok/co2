    r.bold = True
    r.font.size = Pt(16)
    r.font.color.rgb = COLOR_H1
    set_cn_font(r)
    # 俄语副标题
    p.add_run("\n")
    r2 = p.add_run(ru)
    r2.italic = True
    r2.font.size = Pt(10.5)
    r2.font.color.rgb = COLOR_RU
    r2.font.name = RU_FONT


