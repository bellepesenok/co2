def _set_run_font(run, cjk=CJK_FONT, lat=LAT_FONT):
    run.font.name = lat
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:eastAsia"), cjk)
    rfonts.set(qn("w:ascii"), lat)
    rfonts.set(qn("w:hAnsi"), lat)


def shade(paragraph, hex_color):
    """Заливка фона абзаца."""
    pPr = paragraph._p.get_or_add_pPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    pPr.append(shd)


def left_border(paragraph, hex_color, size=24):
    """Цветная вертикальная полоса слева (для блоков-пояснений)."""
    pPr = paragraph._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    left = OxmlElement("w:left")
    left.set(qn("w:val"), "single")
    left.set(qn("w:sz"), str(size))
    left.set(qn("w:space"), "8")
    left.set(qn("w:color"), hex_color)
    pbdr.append(left)
    pPr.append(pbdr)


def add_run(p, text, size=11, bold=False, color=None, italic=False,
            cjk=CJK_FONT, lat=LAT_FONT):
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.bold = bold
    r.italic = italic
    if color is not None:
        r.font.color.rgb = color
    _set_run_font(r, cjk=cjk, lat=lat)
    return r


def h1(text_cn, text_ru=None):
    p = doc.add_paragraph()
    p.space_before = Pt(14)
    add_run(p, text_cn, size=18, bold=True, color=C_TITLE)
    if text_ru:
        p2 = doc.add_paragraph()
        add_run(p2, text_ru, size=11, italic=True, color=C_GREY)
    # нижняя линия
    pPr = p._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "12")
    bottom.set(qn("w:space"), "4")
    bottom.set(qn("w:color"), "8B0000")
    pbdr.append(bottom)
    pPr.append(pbdr)
    return p


def h2(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after = Pt(2)
    add_run(p, text, size=14, bold=True, color=C_H2)
    return p


