# -*- coding: utf-8 -*-
"""
краткий конспект (шпаргалка) — самая суть по пунктам.
Краткая версия для экзамена: китайские тезисы + короткое русское пояснение.
"""
from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

C_TITLE = RGBColor(0xA6, 0x1C, 0x1C)
C_H = RGBColor(0x1F, 0x49, 0x7D)
C_CN = RGBColor(0x20, 0x20, 0x20)
C_RU = RGBColor(0x55, 0x55, 0x55)
CN_FONT = "Microsoft YaHei"
RU_FONT = "Cambria"


def cn_font(run, name=CN_FONT):
    run.font.name = name
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts'); rPr.append(rFonts)
    rFonts.set(qn('w:eastAsia'), name)
    rFonts.set(qn('w:ascii'), name)
    rFonts.set(qn('w:hAnsi'), name)


def shade(p, fill):
    pPr = p._p.get_or_add_pPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), fill)
    pPr.append(shd)


doc = Document()
st = doc.styles['Normal']
st.font.size = Pt(10.5); st.font.name = RU_FONT
st.element.rPr.rFonts.set(qn('w:eastAsia'), CN_FONT)
for s in doc.sections:
    s.left_margin = s.right_margin = Cm(1.8)
    s.top_margin = s.bottom_margin = Cm(1.5)


def title(cn, ru):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(cn); r.bold = True; r.font.size = Pt(16); r.font.color.rgb = C_TITLE; cn_font(r)
    p2 = doc.add_paragraph(); p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r2 = p2.add_run(ru); r2.italic = True; r2.font.size = Pt(10); r2.font.color.rgb = C_RU; r2.font.name = RU_FONT
    p2.paragraph_format.space_after = Pt(6)


def h(cn, ru):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(9); p.paragraph_format.space_after = Pt(2)
    shade(p, "EAF0F6")
    r = p.add_run(cn); r.bold = True; r.font.size = Pt(12.5); r.font.color.rgb = C_H; cn_font(r)
    r2 = p.add_run("  " + ru); r2.italic = True; r2.font.size = Pt(9.5); r2.font.color.rgb = C_RU; r2.font.name = RU_FONT


def pt(cn, ru=None):
    p = doc.add_paragraph(); p.paragraph_format.space_after = Pt(2); p.paragraph_format.line_spacing = 1.1
    p.paragraph_format.left_indent = Cm(0.2)
    r = p.add_run("• " + cn); r.font.size = Pt(10.5); r.font.color.rgb = C_CN; cn_font(r)
    if ru:
        r2 = p.add_run("  — " + ru); r2.italic = True; r2.font.size = Pt(9); r2.font.color.rgb = C_RU; r2.font.name = RU_FONT


title("第三章 对外贸易宏观管理体制改革 · 考点速记",
      "Глава 3. Реформа системы управления внешней торговлей — кратко, по пунктам")

h("0. 概念", "Понятие")
pt("外贸宏观管理体制 = 组织形式、机构、管理权限、经营分工、利益分配的制度。",
   "Система управления ВЭД = институты: кто организует, какие органы, чьи полномочия, кто чем торгует, как делят прибыль.")
pt("由经济基础决定；1978年经济基础变 → 必须改革。", "Базис определяет систему; в 1978 г. базис изменился → нужна реформа.")

h("1. 改革前四大特征", "4 черты дореформенной (плановой) системы")
pt("①单一公有制", "только госсобственность; торгуют ~10 госкомпаний")
pt("②对外贸易统制", "госмонополия, всё по плану (товар, объём, цена)")
pt("③统负盈亏", "прибыль/убыток целиком берёт бюджет — «общий котёл»")
pt("④贸易保护政策", "протекционизм: высокие пошлины + лицензии, квоты, валютный контроль")

h("评价", "Оценка старой системы")
pt("积极：集中资源扩出口、统一安排进口保重点、配合外交破封锁。",
   "Плюсы: концентрация ресурсов, единый импорт, поддержка внешней политики.")
pt("弊端：独家经营产销脱节、高度集中政企不分、统包盈亏缺激励。",
   "Минусы: разрыв производства и рынка, чрезмерная централизация, нет мотивации.")

h("2. 改革与开放的关系 / 目标", "Связь реформы и открытости; цели")
pt("“改革”要求“开放”，“开放”促进“改革”；外贸改革是对外开放的基础和先驱。",
   "Реформа требует открытости и наоборот; торговля — фундамент всей открытости.")
pt("目标：扩大出口(发挥比较优势) + 有选择限制进口(保护产业)。逻辑：消除反出口倾向 + 有选择保护。",
   "Цель: расширить экспорт + выборочно защитить отрасли. Логика: убрать антиэкспортный уклон, сохранить выборочную защиту.")

h("3. 改革的八个方面（核心）", "8 направлений реформы — ГЛАВНОЕ")
pt("①下放经营权、扩大地方自主权", "передать права вниз, дать автономию регионам (но политика осталась)")
pt("②扩大经营渠道、打破垄断", "впустить разные формы собственности; компаний: 10 → 26 тыс. (1999)")
pt("③工贸结合、推行代理制", "соединить производство и торговлю; перейти к агентской схеме")
pt("④缩小计划控制范围", "три режима: директивный/индикативный/рыночный; 1994 — директивный план отменён")
pt("⑤启用关税与非关税手段", "вместо плана — тарифы и нетарифные меры (сначала рост, потом спад; к 2005 квоты/лицензии сняты)")
pt("⑥改革外汇管理体制", "курсовая реформа (см. 4 этапа ниже) — рычаг всей реформы ВЭД")
pt("⑦对外贸易承包经营责任制", "подряд: заморозить субсидии, стимулировать экспорт; переходная, не рыночная форма")
pt("⑧改革统包盈亏财务体制", "统负盈亏→核定补贴→补贴封顶→取消补贴 (экспорт 1991, импорт 1994)")

h("汇率改革四阶段", "4 этапа курсовой реформы (важно знать годы)")
pt("①1979–84：单一→双重→单一汇率（贸易内部价2.80）", "метания курса; торговый курс 2,80 для покрытия убытков")
pt("②1985–93：官方价 + 外汇调剂价并存（双轨）", "два курса параллельно; рыночная доля растёт до ~80%, юань → 5,8")
pt("③1994：汇率并轨 8.70，有管理的浮动汇率制", "объединение курсов (8,70), управляемое плавание, банковская купля-продажа валюты")
pt("④2005：参考一篮子货币、不再盯单一美元", "привязка к корзине валют, более гибкий курс")

h("4. 加入WTO（2001.12）主要承诺", "Вступление в ВТО (дек. 2001): ключевые обязательства")
pt("①非歧视/国民待遇 ②政策统一实施 ③透明度", "недискриминация/нацрежим; единая политика; прозрачность")
pt("④经营权登记制（取消审批） ⑤关税降至约10%(2005)", "право на ВЭД — регистрация; пошлины до ~10%")
pt("⑥取消非关税壁垒(2005) ⑦取消禁止性出口补贴 ⑧执行TRIMs", "снять квоты/лицензии; убрать запрещённые субсидии; TRIMs")
pt("⑨过渡性审议 ⑩特殊保障条款(12年) ⑪反倾销替代价格(15年) ⑫开放服务业",
   "обзоры; спецзащита 12 лет; антидемпинг «суррогатная цена» 15 лет; открытие услуг")

h("5. 总结 / 结论", "Главный вывод")
pt("高保护体制 →（出口鼓励过渡）→ “中性”自由贸易体制（对进出口政策对等）。",
   "От высокого протекционизма → через поощрение экспорта → к НЕЙТРАЛЬНОЙ торговле (симметрия импорт/экспорт).")
pt("渐进式改革：用市场与非市场力量，实现“保护产业+促进出口”双重目标。",
   "Градуализм: рыночные и нерыночные рычаги; двойная цель — защита отраслей + рост экспорта.")

